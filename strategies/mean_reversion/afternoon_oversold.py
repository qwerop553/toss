from ..base import Strategy
from .. import indicators as ind
import pandas as pd


class AfternoonOversoldStrategy(Strategy):
    """
    오후 과매도 → 종가 회귀.

    발굴 근거 (1분봉 이벤트 스터디, 코스피 대형주 8종목 × 52거래일):
      전 구간 평균은 '지금부터 종가까지' -6.7bp로 하락 편향인데, 개장 후 240봉
      (대략 13시) 이후 RSI(14)가 30 아래로 눌린 지점만 골라내면 같은 측정이
      +51.6bp(t=+10.9)로 뒤집힌다. 왕복 슬리피지 23bp를 두 배 넘게 웃도는 폭이다.

    ── 이벤트 스터디 숫자와 실제 체결이 다른 이유 ──
      스터디는 '조건을 만족한 모든 봉'을 평균한다. 전략은 그날 조건을 만족한
      '첫 봉'에서만 산다. 눌림이 깊어질수록 조건은 더 오래 참인데, 전략은 그
      구간의 가장 이른(=가장 덜 극단적인) 지점에 붙는다. 그래서 실현 엣지는
      스터디 값의 대략 절반이다. 아래 '실측'은 실제 체결 기준 숫자다.

    검증 (코스피50 전 종목, 거래당 비용 전 총수익 / 왕복비용 23bp) — 경계선이다:
      파라미터를 고를 때 쓴 30종목  +36.8bp(t=+4.8) 왕복364회 → 비용 후 +13.7bp
      그때 존재하지도 않던 20종목  +24.1bp(t=+3.7) 왕복202회 → 비용 후  +1.0bp
      out-of-sample에서도 총수익은 통계적으로 살아 있지만(t=3.7) 크기가 딱
      왕복비용만큼이라 비용 후로는 본전이다. 종목 단위로 플러스인 비율도 55%로
      동전던지기에 가깝다. '엣지는 있는데 이 비용 구조에서는 못 먹는다'가 결론이다.
      슬리피지 가정이 낮아지거나(대량주문·수수료 우대) 진입을 더 조이면 살아난다.

      파라미터 자체는 튼튼하다: oversold를 20~35, after_bar를 180~270으로 훑은
      12개 조합 전부에서 총수익이 양수였다(+9 ~ +43bp). 한 점만 좋은 게 아니다.

      기본값이 240이 아니라 270인 이유: 훑어 보면 같은 oversold에서 after_bar가
      늦을수록 거의 단조롭게 좋아진다. 남은 봉이 적을수록 '추가 하락에 쓸 시간'이
      줄기 때문이라고 읽었다. 다만 이 선택은 같은 표본에서 고른 값이라 그 자체가
      out-of-sample 근거는 아니다 — 방향(늦을수록 낫다)이 조합 전반에 걸쳐
      일관된다는 점이 근거다.

    왜 오후여야 하나:
      오전의 과매도는 '아직 하루가 안 끝난 하락'이라 더 빠질 시간이 남아 있다.
      실제로 시간대별로 잘라 보면 10:30~13:00 구간은 60분 forward가 -9.5bp
      (t=-9.6)로 오히려 계속 밀린다. 반면 13시 이후의 과매도는 남은 봉이 적어
      추가 하락의 여지가 짧고, 장 마감 전 되돌림·종가 관여 수급이 겹친다.

    왜 진입 시각 하한만 두고 상한은 없나:
      상한을 두면 '오후에 계속 눌려 있다가 14시에 조건을 만족한 날'을 통째로
      버린다. 어차피 청산이 그날 마지막 봉이라 늦게 들어갈수록 보유 시간이 짧아질
      뿐 규칙이 깨지지 않는다. 다만 마감 직전에 진입하면 그 자리에서 청산되어
      비용만 나가므로 max_entry_bar(≈15:15)로 뒤쪽을 잘라 둔다.

    청산은 그날 마지막 봉뿐이다. 손절이 없는 이유:
      이 알파는 '눌린 자리에서 종가까지'라는 구간 자체에 붙어 있다. 중간에 더
      빠졌다고 끊으면 되돌림이 오기 직전에 나가는 꼴이라, 이벤트 스터디에서 본
      +51.6bp가 남지 않는다. 대신 오버나잇을 하지 않아 손실이 하루로 제한된다.

    ※ 전제조건: 분봉 데이터. 일봉에서는 '오후'가 존재하지 않는다.
    """

    def __init__(self, period=14, oversold=30, after_bar=270, max_entry_bar=375):
        self.period = period
        self.oversold = oversold
        self.after_bar = after_bar          # 개장 후 이 순번부터 진입 허용 (270 ≈ 13:30)
        self.max_entry_bar = max_entry_bar  # 이 순번을 넘으면 진입 금지 (375 ≈ 15:15)
        self.warmup = period

    def entries(self, df: pd.DataFrame) -> pd.Series:
        # [매수] 오후 구간 + RSI 과매도. 마감 직전 진입은 순번 상한으로 막는다.
        # '남은 봉 수'로 재지 않는 이유: 하루의 총 봉 수는 장이 끝나야 확정되는
        # 값이라, 그걸 오후 봉의 진입 조건에 쓰면 미래를 보는 셈이 된다.
        rsi = ind.rsi(df["close"], self.period)
        bar_no = ind.bar_of_day(df)
        return ((bar_no >= self.after_bar)
                & (bar_no <= self.max_entry_bar)
                & (rsi < self.oversold))

    def exits(self, df: pd.DataFrame) -> pd.Series:
        # [매도] 그날 마지막 봉. 오버나잇 금지가 유일한 청산 규칙이다.
        return ind.is_last_bar_of_day(df)
