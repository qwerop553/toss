# -*- coding: utf-8 -*-
from ..base import Strategy
from .. import indicators as ind
import pandas as pd


class OvernightInventoryStrategy(Strategy):
    """
    오버나잇 재고 위험 프리미엄. 종가에 사서 다음 날 시가에 판다.

    마켓메이커는 장 마감 전에 재고를 턴다. 장이 닫힌 동안에는 헤지도 청산도 못 하는데
    갭 위험은 열려 있기 때문이다. 그런데 누군가는 그 재고를 밤새 들고 있어야 하고,
    그 대가가 오버나잇 수익률에 실린다는 것이 이 전략의 전제다. 이 패키지에서 유일하게
    **마켓메이커 고유의 제약**(재고 위험)을 직접 겨냥한다 — 나머지 넷은 유동성의
    값을 재는 일반적인 추정량이다.

    구현: 그날 마지막 봉에서 매수, 다음 날 첫 봉에서 매도. 정확히 오버나잇 구간만
    보유한다.

    ※ **분봉 전용이다.** 일봉에서는 종가와 다음 시가 사이를 분리할 수 없다. 엔진이
      모든 체결을 봉의 close에 내므로 일봉으로 돌리면 '종가 매수 → 다음 종가 매도'가
      되어 오버나잇이 아니라 하루 전체를 들고 있게 된다. 이 리포의 분봉은 종목당
      28거래일뿐이라, 다른 넷과 달리 검정력이 크게 떨어진다는 것을 감안하고 봐라.

    ── 검증 (코스피50 1분봉, 50종목 × 28거래일, 오버나잇 이벤트 1,395회) ──
        오버나잇 수익(비용 전)  +21.27bp  (t=+3.2)
        비용 후                  -1.78bp   승률 47.0%  종목양수 34%
        (비교) 같은 종목 장중 수익  -12.93bp (t=-1.5)

      **효과 자체는 실재하고 방향도 문헌과 맞는다.** 같은 종목·같은 기간에서 밤사이
      +21bp, 장중 -13bp다. 하루의 수익이 사실상 전부 장 밖에서 난다는 주식시장의
      알려진 성질이 이 표본에서도 그대로 나온다. 재고를 밤새 들고 있는 쪽이 대가를
      받는다는 전제와 부합한다.

      그리고 왕복비용 23bp를 2bp 차이로 못 넘는다. 다섯 중 가장 아깝게 실패했다.
      매도 슬리피지 0.215%(거래세 포함)가 그대로 걸리는 구조라, 세금이 없는 계좌나
      비용 가정이 낮은 환경에서는 결론이 뒤집힌다 — 엣지가 없어서 진 것이 아니라
      비용 가정에 진 것이므로 그 가정을 바꿀 이유가 생기면 다시 재 볼 값어치가 있다.

      ※ 표본 주의: 1,395회는 50종목 × 28일이라 같은 날짜를 50번 세는 셈이다.
        실효 표본은 28에 가깝고, t=3.2는 그만큼 부풀려져 있다.

    ※ 점수형이 아니라 시각 규칙이라 PercentileScoreStrategy를 쓰지 않는다.
    """

    def __init__(self, min_bars_per_day=60):
        # 반나절 장(폐장일 등)은 오버나잇 성격이 달라 건너뛴다
        self.min_bars_per_day = min_bars_per_day

    def _full_day(self, df: pd.DataFrame) -> pd.Series:
        d = ind.bar_dates(df)
        return df.groupby(d)["close"].transform("size") >= self.min_bars_per_day

    def entries(self, df: pd.DataFrame) -> pd.Series:
        # [매수] 그날 마지막 봉. 여기서부터 다음 시가까지가 오버나잇 구간이다.
        # 데이터 전체의 마지막 봉도 is_last_bar_of_day가 True를 내는데, 그 자리는
        # 다음 날이 없어 청산이 안 된다 — 미청산 포지션으로 리포트에 따로 잡힌다.
        return ind.is_last_bar_of_day(df) & self._full_day(df)

    def exits(self, df: pd.DataFrame) -> pd.Series:
        # [매도] 그날 첫 봉. 진입 다음 봉이라 항상 진입보다 뒤에 온다.
        return ind.bar_of_day(df) == 0
