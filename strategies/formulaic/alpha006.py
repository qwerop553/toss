# -*- coding: utf-8 -*-
from .base import FormulaicAlpha, correlation
import pandas as pd


class Alpha006Strategy(FormulaicAlpha):
    """
    WorldQuant Alpha#6:

        (-1 * correlation(open, volume, 10))

    최근 10봉 동안 **시가와 거래량이 같이 움직였는지**를 보고, 그 상관계수의 부호를
    뒤집어 알파로 쓴다. 상관이 음수일수록(= 가격이 오를 때 거래가 줄고, 내릴 때
    늘어나는 구간) 알파가 커진다.

    해석: 가격과 거래량이 나란히 오르는 구간은 이미 모두가 알고 붙은 구간이다. 반대로
    조용히 오르거나 거래가 실린 채 눌린 구간은 아직 반영이 덜 됐다고 본다. 가격 수준도
    방향도 보지 않고 **두 시계열의 동조 여부만** 본다는 점이 이 리포의 다른 전략들과
    근본적으로 다르다 — 상관계수는 스케일이 없어서 종목·가격대에 무관하다.

    왜 종가가 아니라 시가인가: 논문의 알파들이 open을 쓸 때는 보통 '그 봉에 새로
    유입된 정보'를 뜻한다. 종가는 직전 봉의 결과를 물고 있어 거래량과의 동조가
    자기상관에 오염되기 쉽다.

    ── 검증 (코스피 대형주 43종목 일봉, 1975~2026) ──
      측정 기준은 '보유 중 봉당 수익 - 미보유 봉당 수익'이다. 거래당 수익으로 재면
      일봉에서 오래 들고 있는 전략이 시장 상승을 그대로 먹어 무조건 좋아 보인다.

        train(~2014)  초과 +4.52bp/봉 (t=+2.9)  비용 1.68  순 +2.84
        test (2015~)  초과 +2.57bp/봉 (t=+1.4)  비용 1.83  순 +0.74
        격자 18조합 중 순알파 양수: train 67% / test 83%

      **양쪽 구간에서 모두 양수인 유일한 전략이다.** 이 리포에서 만든 것 중 유일하게
      레짐을 타지 않는다 — microstructure 패키지의 RollSpread·OFI는 test에서 훨씬
      크지만 train에서는 격자의 22%·6%만 양수라, 2015년 이후 평균회귀 레짐을 타고
      있는 것이다(strategies/microstructure/base.py의 요약표). 다만 test t=1.4로
      통계적으로는 약하다. 이 전략의 미덕은 크기가 아니라 안정성이다 — window/entry_q/exit_q를
      훑은 18개 조합 중 13개가 train에서 순알파 양수였고, 회전율이 낮아(평균 보유
      14봉) 비용이 1.6bp/봉밖에 안 든다. Alpha#101처럼 신호는 크지만 이틀 만에
      사라지는 것과 정반대 성격이다.

      기본값 entry_q=0.95 / exit_q=0.3은 train 구간에서 고른 값이고 test에서 위
      숫자로 확인했다. 다른 넷은 중립값(0.8/0.5)을 그대로 둔다.

    ※ 10봉 내내 거래량이 일정하면(호가가 안 붙은 종목의 빈 구간) 분모가 0이라
      상관계수가 NaN이 된다. to_signals가 NaN을 False로 눌러 신호를 내지 않는다.
    """

    lookback = 10
    entry_q = 0.95   # train에서 고름. 아래 검증 참고
    exit_q = 0.3

    def alpha(self, df: pd.DataFrame) -> pd.Series:
        return -1 * correlation(df["open"], df["volume"], 10)
