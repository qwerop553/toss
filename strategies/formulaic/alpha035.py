# -*- coding: utf-8 -*-
from .base import FormulaicAlpha, ts_rank
import pandas as pd


class Alpha035Strategy(FormulaicAlpha):
    """
    WorldQuant Alpha#35:

        ((Ts_Rank(volume, 32) * (1 - Ts_Rank(((close + high) - low), 16)))
         * (1 - Ts_Rank(returns, 32)))

    세 개의 시계열 순위를 곱한다. 전부 [0,1]이라 곱도 [0,1]이고, 세 조건이 **동시에**
    만족될 때만 값이 커진다 — AND 게이트를 곱셈으로 만든 것이다.

      Ts_Rank(volume, 32)              거래량이 최근 32봉 중 높은 편인가      (↑일수록 큼)
      1 - Ts_Rank(close+high-low, 16)  가격 수준이 최근 16봉 중 낮은 편인가   (↓일수록 큼)
      1 - Ts_Rank(returns, 32)         최근 수익률이 32봉 중 낮은 편인가      (↓일수록 큼)

    합치면 '**거래는 터졌는데 가격은 눌려 있고 수익률도 나쁜 자리**'다. 투매 뒤 바닥을
    사는 고전적인 형태를 순위 세 개로 표현했다. 어느 하나라도 0에 가까우면 곱이 0으로
    죽기 때문에, 셋 중 둘만 맞는 자리는 걸러진다.

    `(close + high) - low`가 가격 수준의 대리변수인 이유: 종가·고가는 더하고 저가는
    뺀다. 저가가 낮게 찍힌 봉일수록 값이 작아져서, 단순 종가보다 '아래로 꼬리를 단
    봉'을 낮게 평가한다. 세 항 중 유일하게 창이 16봉으로 짧은 것도 가격 위치는 더
    최근 기준으로 봐야 한다는 뜻으로 읽힌다.

    returns는 논문 정의상 종가 대 종가 수익률이다.

    ── 검증 (코스피 대형주 43종목 일봉, 1975~2026) ── 부호가 반대다
        train(~2014)  초과 -3.71bp/봉 (t=-3.0)  비용 1.57  순 -5.28
        test (2015~)  초과 -2.24bp/봉 (t=-1.5)  비용 1.59  순 -3.83

      훑어본 18개 조합 중 **train에서 순알파가 양수인 것이 하나도 없다**(0/18).
      train·test 양쪽에서 일관되게 음수라는 건 노이즈가 아니라 '한국 대형주에서는
      이 조건이 반대로 작동한다'는 뜻이다. 거래량이 터지고 가격이 눌린 자리는
      바닥이 아니라 계속 빠지는 자리였다.

      뒤집으면 양수가 되겠지만 그렇게 하지 않았다. 부호를 데이터에 맞춰 뒤집는
      순간 논문의 알파가 아니라 이 표본에 맞춘 다른 전략이 된다.

    ※ 세 순위의 곱이라 분포가 0 쪽으로 심하게 쏠린다. 그래서 절대 임계값이 아니라
      베이스의 자기 백분위 변환이 특히 중요하다.
    """

    lookback = 32

    def alpha(self, df: pd.DataFrame) -> pd.Series:
        returns = df["close"].pct_change()
        return (ts_rank(df["volume"], 32)
                * (1 - ts_rank((df["close"] + df["high"]) - df["low"], 16))
                * (1 - ts_rank(returns, 32)))
