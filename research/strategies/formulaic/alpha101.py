# -*- coding: utf-8 -*-
from .base import FormulaicAlpha
import pandas as pd


class Alpha101Strategy(FormulaicAlpha):
    """
    WorldQuant Alpha#101:

        ((close - open) / ((high - low) + .001))

    논문 101개 중 가장 짧다. 한 봉의 몸통(종가-시가)을 전체 범위(고가-저가)로 나눈 값,
    즉 **그 봉에서 매수측이 얼마나 이겼나**를 -1~+1로 잰다. +1에 가까우면 저가에서
    열려 고가에서 닫힌 봉이고, -1에 가까우면 반대다. `.001`은 고가=저가인 봉(거래가
    한 가격에서만 난 봉)에서 0으로 나누는 것을 막는 가드다.

    캔들 차트의 '장대양봉'을 수식 하나로 옮긴 것이라 볼 수 있는데, 중요한 차이가 있다.
    이건 몸통의 절대 크기가 아니라 **범위 대비 비율**이다. 크게 움직였지만 위아래로
    흔들리다 제자리에 온 봉은 0에 가깝고, 조금 움직였어도 한 방향으로만 간 봉은 1에
    가깝다. 방향의 순도를 재지 변동성을 재지 않는다.

    이 리포에는 없던 재료다. HeikinAshiTrendStrategy가 봉 모양을 보긴 하지만 그쪽은
    평활화된 가짜 봉이고, 이쪽은 원본 봉 하나만 본다.

    베이스가 이 값을 최근 window봉의 자기 백분위로 바꿔 상위 20%에서 진입한다.

    ── 검증 (코스피 대형주 43종목 일봉, 1975~2026) ── 부호가 뒤집혔다
        train(~2014)  초과 +16.37bp/봉 (t=+11.8)  비용 11.54  순  +4.83
        test (2015~)  초과  -9.56bp/봉 (t= -5.8)  비용 11.99  순 -21.56

      이 리포에서 본 것 중 in-sample 신호가 가장 강했다(t=11.8). 그리고 out-of-sample
      에서 부호까지 뒤집혔다(t=-5.8). 2014년까지의 한국 일봉에는 '오늘 강한 봉이면
      내일도 강하다'는 1봉 모멘텀이 있었고 2015년 이후로는 역전됐다는 뜻이다.
      t가 크다는 것이 지속성을 보장하지 않는다는 사례로 남겨 둔다.

      비용도 별개로 치명적이다. 평균 보유가 2봉이라 왕복 23bp가 봉당 11.5bp로 얹힌다.
      히스테리시스를 넓혀 보유를 10봉으로 늘리면 비용은 2.3bp로 떨어지지만 초과수익이
      -2.9bp가 된다 — 엣지가 애초에 1~2봉짜리라 오래 들면 사라진다. 회전율과 엣지를
      맞바꿀 수 없는 구조다.
    """

    lookback = 0  # 현재 봉만 본다

    def alpha(self, df: pd.DataFrame) -> pd.Series:
        return (df["close"] - df["open"]) / ((df["high"] - df["low"]) + .001)
